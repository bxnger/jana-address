"""Очистка «шума» реальных заказов перед ядром разбора.

В строке доставки часто есть то, что не является адресом: телефон, код домофона,
опечатки в служебных словах («падъезд», «квартра»). Ядру они мешают: телефон
принимается за дом, «код 1234» — за улицу. Здесь убираем только то, что
распознаётся однозначно; названия улиц и номера домов не трогаем.

raw_address в ответе остаётся исходным — очищенная строка уходит только в ядро.
Что убрано, видно в debug-ответе (_noise).
"""
from __future__ import annotations

import re

# Казахстанский номер: 8 / +7, затем 10 цифр, начинающихся с 7 (мобильные 7xx и городские 7xxx),
# с любыми пробелами, дефисами и скобками; необязательный префикс «тел», «т.», «телефон»
_PHONE = re.compile(
    r"(?i)(?:\b(?:тел(?:ефон)?|т|tel|phone)\.?\s*:?\s*)?"
    r"(?<!\d)(?:\+\s?7|8)[\s\-()]*7\d{2}[\s\-()]*\d{3}[\s\-]*\d{2}[\s\-]*\d{2}(?!\d)"
)
# Код домофона: «код домофона 12К», «код 1234#», «домофон 45», «домофон не работает»
_INTERCOM = re.compile(
    r"(?i)\b(?:код\s+домофона|домофон|код)(?:\s+не\s+работает)?\s*[:\-№]?\s*(?:[\dA-Za-zА-Яа-я]{1,6}[#*]?)?(?=\s*(?:,|$))"
)
# Опечатки в служебных словах (только сами слова — названия не трогаем)
_TYPOS = [
    (re.compile(r"(?i)\bпа(дъ|дь|д)езд"), lambda m: "подъезд"),
    (re.compile(r"(?i)\bквартра\b"), lambda m: "квартира"),
    (re.compile(r"(?i)\bкватира\b"), lambda m: "квартира"),
    (re.compile(r"(?i)\bетаж"), lambda m: "этаж"),
]


def strip_noise(text: str | None) -> tuple[str | None, list[str]]:
    """-> (строка для ядра, что убрано/исправлено)."""
    if not text or not isinstance(text, str):
        return text, []
    removed = []

    def cut(rx, s, label):
        def repl(m):
            removed.append(f"{label}: {m.group(0).strip()}")
            return " "
        return rx.sub(repl, s)

    s = cut(_PHONE, text, "телефон")
    # код домофона — только отдельным фрагментом: «..., код 1234#» / «... домофон 45»
    s = cut(_INTERCOM, s, "домофон")
    for rx, fix in _TYPOS:
        if rx.search(s):
            removed.append(f"опечатка: {rx.search(s).group(0)}")
            s = rx.sub(fix, s)
    if not removed:
        return text, []
    # подчистить висячие запятые и пробелы после вырезания
    s = re.sub(r"\s*,\s*(,\s*)+", ", ", s)
    s = re.sub(r"^[\s,]+|[\s,]+$", "", s)
    s = re.sub(r"\s{2,}", " ", s)
    return s, removed
